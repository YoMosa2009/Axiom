[CmdletBinding()]
param(
    [Parameter()]
    [ValidateSet('linux-x64', 'win-x64')]
    [string]$Runtime = 'linux-x64',

    [Parameter()]
    [string]$OutputDir = (Join-Path $env:LOCALAPPDATA 'Axiom\LiveDeploy')
)

$ErrorActionPreference = 'Stop'

function Read-PlainSecret {
    param([Parameter(Mandatory)][string]$Prompt)
    $sec = Read-Host -Prompt $Prompt -AsSecureString
    $ptr = [System.Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec)
    try {
        return [System.Runtime.InteropServices.Marshal]::PtrToStringBSTR($ptr).Trim()
    }
    finally {
        [System.Runtime.InteropServices.Marshal]::ZeroFreeBSTR($ptr)
    }
}

$repoRoot = Split-Path -Path $PSScriptRoot -Parent
$gatewayProj = Join-Path $repoRoot 'tools\AxiomSubscriptionGateway\AxiomSubscriptionGateway.csproj'
$deployDir = Join-Path $repoRoot 'tools\AxiomSubscriptionGateway\deploy'
if (-not (Test-Path $gatewayProj)) { throw "Gateway project not found: $gatewayProj" }

Write-Host '=== Axiom Cloud Live Gateway Wizard ==='
$originInput = (Read-Host -Prompt 'Public HTTPS origin for your gateway (e.g. https://api.axiominference.work)').Trim().TrimEnd('/')
if (-not [Uri]::TryCreate($originInput, [UriKind]::Absolute, [ref]([Uri]$null)) -or -not $originInput.StartsWith('https://', [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Public origin must be a valid https:// URL.'
}

$stripeLiveKey = Read-PlainSecret -Prompt 'Stripe LIVE secret key (sk_live_... or rk_live_...)'
if (-not ($stripeLiveKey.StartsWith('sk_live_') -or $stripeLiveKey.StartsWith('rk_live_'))) {
    throw 'Expected a Stripe live secret key starting with sk_live_ or rk_live_.'
}

$provider = (Read-Host -Prompt 'Upstream AI provider [digitalocean / deepseek / openrouter] (recommended: digitalocean)').Trim().ToLowerInvariant()
if ($provider -notin @('digitalocean', 'deepseek', 'openrouter')) {
    throw "Unsupported provider '$provider'. Choose digitalocean, deepseek, or openrouter."
}
$upstreamKey = Read-PlainSecret -Prompt "Upstream API key for $provider"
if ([string]::IsNullOrWhiteSpace($upstreamKey)) { throw 'Upstream API key cannot be empty.' }

$smtpHost = (Read-Host -Prompt 'SMTP host for login verification codes (e.g. smtp.resend.com)').Trim()
$smtpPort = (Read-Host -Prompt 'SMTP port [587]').Trim()
if ([string]::IsNullOrWhiteSpace($smtpPort)) { $smtpPort = '587' }
$smtpUser = (Read-Host -Prompt 'SMTP username').Trim()
$smtpPass = Read-PlainSecret -Prompt 'SMTP password / API key'
$smtpFrom = (Read-Host -Prompt 'From address (e.g. Axiom Cloud <noreply@axiominference.work>)').Trim()

New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null
$stripePartialEnv = Join-Path $OutputDir '.stripe-provisioned.env'
$finalEnv = Join-Path $OutputDir 'gateway.env'

Write-Host "`n1/4 Provisioning Stripe live Price (`$9/mo`), Portal & Webhook via AxiomSubscriptionGateway --provision-live..."
$prevStripeKey = $env:AXIOM_STRIPE_SECRET_KEY
try {
    $env:AXIOM_STRIPE_SECRET_KEY = $stripeLiveKey
    dotnet run --project $gatewayProj -c Release -- --provision-live $originInput --write-env $stripePartialEnv
    if ($LASTEXITCODE -ne 0) { throw 'Live Stripe provisioning failed.' }
}
finally {
    if ($null -eq $prevStripeKey) { Remove-Item Env:AXIOM_STRIPE_SECRET_KEY -ErrorAction SilentlyContinue }
    else { $env:AXIOM_STRIPE_SECRET_KEY = $prevStripeKey }
}

Write-Host "`n2/4 Generating production gateway.env bundle in $OutputDir (kept outside git)..."
$provisionedLines = Get-Content -Path $stripePartialEnv
Remove-Item -LiteralPath $stripePartialEnv -Force -ErrorAction SilentlyContinue

$dbPath = if ($Runtime -eq 'linux-x64') { '/var/lib/axiom-gateway/axiom-accounts.sqlite' } else { Join-Path $OutputDir 'axiom-accounts.sqlite' }
$bkpPath = if ($Runtime -eq 'linux-x64') { '/var/lib/axiom-gateway/backups' } else { Join-Path $OutputDir 'backups' }

$envContent = @(
    '# Generated by Setup-AxiomLiveGateway.ps1 — KEEP CONFIDENTIAL'
    'AXIOM_PORT=5198'
    "AXIOM_ACCOUNTS_DB=$dbPath"
    "AXIOM_BACKUP_DIR=$bkpPath"
    'AXIOM_BACKUP_INTERVAL_HOURS=6'
    'AXIOM_MONTHLY_ALLOWANCE_MICROS=5250000'
    "AXIOM_STRIPE_SECRET_KEY=$stripeLiveKey"
) + $provisionedLines + @(
    "AXIOM_UPSTREAM_PROVIDER=$provider"
    "AXIOM_UPSTREAM_API_KEY=$upstreamKey"
    "AXIOM_SMTP_HOST=$smtpHost"
    "AXIOM_SMTP_PORT=$smtpPort"
    "AXIOM_SMTP_USERNAME=$smtpUser"
    "AXIOM_SMTP_PASSWORD=$smtpPass"
    "AXIOM_SMTP_FROM=$smtpFrom"
)
[System.IO.File]::WriteAllLines($finalEnv, $envContent, [System.Text.UTF8Encoding]::new($false))

Write-Host "`n3/4 Publishing self-contained AxiomSubscriptionGateway for $Runtime..."
$pubDir = Join-Path $OutputDir "publish-$Runtime"
dotnet publish $gatewayProj -c Release -r $Runtime --self-contained true -o $pubDir
if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed for $Runtime." }

Copy-Item (Join-Path $deployDir 'axiom-gateway.service') (Join-Path $OutputDir 'axiom-gateway.service') -Force
$hostOnly = ([Uri]$originInput).Host
$caddy = (Get-Content -Raw (Join-Path $deployDir 'Caddyfile.template')).Replace('api.example.com', $hostOnly)
[System.IO.File]::WriteAllText((Join-Path $OutputDir 'Caddyfile'), $caddy, [System.Text.UTF8Encoding]::new($false))

$setGh = (Read-Host -Prompt "`n4/4 Upload AXIOM_BUILTIN_MANAGED_GATEWAY_URL=$originInput/v1 to GitHub Actions secrets? [y/N]").Trim().ToLowerInvariant()
if ($setGh -eq 'y') {
    "$originInput/v1" | gh secret set AXIOM_BUILTIN_MANAGED_GATEWAY_URL --repo YoMosa2009/Axiom
    if ($LASTEXITCODE -ne 0) { throw 'Failed to set AXIOM_BUILTIN_MANAGED_GATEWAY_URL secret on GitHub.' }
    Write-Host 'Updated GitHub secret AXIOM_BUILTIN_MANAGED_GATEWAY_URL.'
}

Write-Host "`nDone! Deployment bundle ready in: $OutputDir"
Write-Host " - Binary: $pubDir"
Write-Host " - Env file: $finalEnv"
Write-Host " - Caddyfile & systemd service: $OutputDir"
